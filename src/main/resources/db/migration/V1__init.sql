-- Esquema inicial de Ranking: replica exactamente lo que Hibernate venia
-- generando con ddl-auto=update, para poder pasar a ddl-auto=validate.

-- Copia local de un resultado de partido, tal como llega en el mensaje
-- resultado.registrado publicado por MS-Competencia. partido_id NO se
-- genera aqui: es el mismo id que usa Competencia
CREATE TABLE resultado_procesado (
    partido_id             BIGINT       NOT NULL,
    competencia_id         BIGINT       NOT NULL,
    deporte_id             BIGINT       NOT NULL,
    version                INTEGER      NOT NULL,
    equipo_local_id        BIGINT       NOT NULL,
    equipo_visita_id       BIGINT       NOT NULL,
    institucion_local_id   BIGINT       NOT NULL,
    institucion_visita_id  BIGINT       NOT NULL,
    puntaje_local          INTEGER,
    puntaje_visita         INTEGER,
    puntos_victoria        INTEGER,
    puntos_empate          INTEGER,
    puntos_derrota         INTEGER,
    CONSTRAINT pk_resultado_procesado PRIMARY KEY (partido_id)
);

-- Fila de la tabla de posiciones de una competencia. Un mismo equipo puede
-- tener una fila por cada competencia en la que participa.
CREATE TABLE fila_tabla (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    competencia_id  BIGINT  NOT NULL,
    equipo_id       BIGINT  NOT NULL,
    institucion_id  BIGINT  NOT NULL,
    pj              INTEGER,
    pg              INTEGER,
    pe              INTEGER,
    pp              INTEGER,
    puntos_favor    INTEGER,
    puntos_contra   INTEGER,
    diferencia      INTEGER,
    pts             INTEGER,
    posicion        INTEGER,
    CONSTRAINT pk_fila_tabla PRIMARY KEY (id),
    CONSTRAINT uk_fila_tabla_competencia_equipo UNIQUE (competencia_id, equipo_id)
);

-- Ranking historico de un equipo en un deporte, acumulado entre todas sus
-- competencias (a diferencia de fila_tabla, que es por competencia).
CREATE TABLE ranking_historico (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    deporte_id      BIGINT  NOT NULL,
    equipo_id       BIGINT  NOT NULL,
    institucion_id  BIGINT  NOT NULL,
    pj              INTEGER,
    pg              INTEGER,
    pe              INTEGER,
    pp              INTEGER,
    puntos_favor    INTEGER,
    puntos_contra   INTEGER,
    diferencia      INTEGER,
    pts             INTEGER,
    posicion        INTEGER,
    CONSTRAINT pk_ranking_historico PRIMARY KEY (id),
    CONSTRAINT uk_ranking_historico_deporte_equipo UNIQUE (deporte_id, equipo_id)
);
